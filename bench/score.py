"""Defender-side scorer: compares tickets with the ground-truth issue list and writes the report.

Lives outside ``preflight/`` on purpose: the agent never sees the ground truth. Run after a demo:
``python -m bench.score``.
"""

from __future__ import annotations

import json
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
SEEDS = ROOT / "seeds" / "seeds.yaml"

# Which seeded issues each invariant's variation can surface (defender knowledge, by inspection).
SEED_MAP: dict[str, list[str]] = {
    "INV-01": ["S08"], "INV-02": ["S01"], "INV-03": ["S04"], "INV-05": ["S09"],
    "INV-08": ["S15", "S17"],
}
OUT_OF_MVP = {"injection", "server_side", "auth_session", "api_hygiene"}  # named in the spec


def _load(path: Path, default: Any) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return default


def score(out_dir: Path = ROOT / "out", seeds_path: Path = SEEDS) -> dict[str, Any]:
    have_truth = seeds_path.exists()  # seeds/ is private and git-ignored: absent in a fresh clone
    seeds = yaml.safe_load(seeds_path.read_text(encoding="utf-8"))["seeds"] if have_truth else []
    tickets = _load(out_dir / "tickets.json", [])
    state = _load(out_dir / "state.json", {})
    found_ids = sorted({s for t in tickets for s in SEED_MAP.get(t["invariant_id"], [])})
    unmatched = [t["id"] for t in tickets if not SEED_MAP.get(t["invariant_id"])]
    misses = []
    for s in seeds:
        if s["id"] in found_ids:
            continue
        why = ("class out of MVP scope (named in the spec)" if s["class"] in OUT_OF_MVP
               else "covered class, but none of the 8 spec variations exercises it")
        misses.append({"id": s["id"], "class": s["class"], "title": s["title"], "reason": why})
    by_class: dict[str, list[int]] = {}
    for s in seeds:
        c = by_class.setdefault(s["class"], [0, 0])
        c[1] += 1
        c[0] += 1 if s["id"] in found_ids else 0
    sb = state.get("scoreboard", {})
    result = {
        "ground_truth": have_truth, "total": len(seeds) if have_truth else None,
        "found": len(found_ids), "found_ids": found_ids, "misses": misses,
        "by_class": {k: f"{v[0]}/{v[1]}" for k, v in by_class.items()},
        "findings": len(tickets), "unmatched_findings": unmatched,
        "precision": (1 - len(unmatched) / len(tickets)) if tickets else None,
        "false_positives_clean_build": sb.get("false_positives_clean_build"),
        "deploy_to_first_proof_s": sb.get("deploy_to_first_proof_s"),
        "tickets_resolved": f"{sb.get('resolved', 0)}/{sb.get('findings', 0)}",
        "checks": {k: {"vulnerable_build": v["status"], "after_fix": v.get("after_fix")}
                   for k, v in state.get("checks", {}).items()},
        "safety": state.get("safety", {}), "llm": state.get("llm", {}),
    }
    (out_dir / "score.json").write_text(json.dumps(result, indent=1), encoding="utf-8")
    return result


def _commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True,
                              text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def write_report(r: dict[str, Any], path: Path = ROOT / "docs" / "BENCHMARKS.md") -> None:
    saf = r["safety"]
    rows = "\n".join(f"| {k} | {v['vulnerable_build']} | {v['after_fix']} |" for k, v in sorted(r["checks"].items()))
    cls = "\n".join(f"| {k} | {v} |" for k, v in sorted(r["by_class"].items()))
    miss = "\n".join(f"- **{m['id']}** ({m['class']}): {m['title']}: {m['reason']}" for m in r["misses"])
    if not r["ground_truth"]:
        raise ValueError("cannot write the benchmark report without the ground-truth issue list")
    prec = "n/a" if r["precision"] is None else f"{r['precision']:.0%}"
    text = f"""# Benchmarks

Generated by `python -m bench.score` after `make demo`. Commit `{_commit()}`, {time.strftime('%Y-%m-%d')}.

## Result (MVP: 8 property checks)

| Metric | Value |
|---|---|
| Recall on the seeded target | **{r['found']} / {r['total']}** ({r['found'] / r['total']:.0%}) |
| Precision (findings that match a seeded issue) | {prec} ({r['findings']} findings, {len(r['unmatched_findings'])} unmatched) |
| False positives on the fixed build (regression sweep) | {r['false_positives_clean_build']} |
| Deploy to first proof | {r['deploy_to_first_proof_s']} s |
| Tickets resolved by the retest after the fix | {r['tickets_resolved']} |
| Out-of-scope requests sent | {saf.get('out_of_scope_sent')} |
| Requests sent / held for approval | {saf.get('requests_sent')} / {saf.get('held_for_approval')} |
| Audit chain valid | {saf.get('audit_chain_ok')} |

Seeded issues found: {', '.join(r['found_ids'])}.

## Per check

| Invariant | Vulnerable build | After the fix deploy (regression sweep) |
|---|---|---|
{rows}

INV-04, INV-06 and INV-07 report *clean* on the vulnerable build. That is correct, not a miss: the
target already enforces those rules (the pay route always checks the amount, refunding a never-paid
booking returns 409, and cancel is tenant-scoped), so they act as precision checks.

## Recall by class

| Class | Found / seeded |
|---|---|
{cls}

## Misses (listed honestly)

{miss}

The spec expected the 8 checks to cover about 11 of the 20 seeded issues; they cover {r['found']}.
Injection, session/auth and server-side classes are deliberately out of MVP scope and are future work.

## What this is not (read before quoting the numbers)

- **Not blind.** The seeded issue list and the target were written by the same team that built the
  agent, so recall here is a regression score, not a generalisation claim. The planned blind
  benchmarks (OWASP crAPI, VAmPI, a teammate-seeded app) have **not been run**.
- **The LLM step is a replay.** Invariants and plans come from `demo/recordings/` which are
  *{r['llm'].get('source', 'unknown')}*. Until a live model produces the recording, the demo shows the
  pipeline around the model (validation, human confirmation, deterministic verification), not
  model quality.
- Severity amounts in tickets are assumptions for the synthetic app, not TBO figures.
- Reserved actions (pay, cancel, refund) need a human approval each; `make demo` uses a scripted
  operator named `demo-operator` for that, shown on screen.
"""
    path.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    res = score()
    if not res["ground_truth"]:
        print("seeds/seeds.yaml not found: the ground truth is private, so no report was written.")
        raise SystemExit(0)
    write_report(res)
    print(f"recall {res['found']}/{res['total']}; findings {res['findings']}; report written", file=sys.stdout)
